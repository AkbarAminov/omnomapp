-- Возврат напоминания к строгому согласию. NOT applied automatically: как и остальные файлы
-- здесь, прогоняется руками.
--
-- Предыстория: несколько часов 2026-10-17 бот подписывал на напоминание автоматически, при
-- любом обращении (ensureSubscribed с ON CONFLICT DO NOTHING). Теперь подписка создаётся
-- только по явному нажатию кнопки «🔔 Напоминать про обед».
--
-- ВАЖНО, прочитать до запуска. Отличить «подписался сам» от «подписан автоматически» в
-- текущей схеме НЕЛЬЗЯ: обе ветки писали одну и ту же строку opted_in = true, отдельной
-- отметки о согласии не существует. Поэтому «кроме тех, кто явно включал» технически
-- невыполнимо для уже накопленных строк, и выбран безопасный вариант: снять всех. Кто
-- захочет, включит заново кнопкой, это одно нажатие. Обратное решение (оставить всех
-- подписанными) означало бы рассылку людям, которые согласия не давали.
--
-- Строки не удаляем, а гасим флаг: сам chat_id ещё нужен, чтобы помнить про отказ и не
-- подписать человека повторно, плюс сохраняется last_reminded_at.
update public.reminder_subscribers
set opted_in = false
where opted_in = true;

-- Групповых чатов в подписчиках быть не должно вовсе: напоминания шлются только в личку.
-- У групп и супергрупп идентификатор отрицательный.
delete from public.reminder_subscribers
where chat_id < 0;

